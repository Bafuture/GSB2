package com.example.saga.core;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Timestamp;
import java.sql.Types;
import java.time.Instant;
import java.util.ArrayList;
import java.util.List;

/**
 * JDBC (embedded H2) persistence for saga instances, step instances and the event
 * timeline. All state transitions of the engine go through this repository, so a
 * restarted process can resume exactly where the previous one stopped.
 */
public class SagaRepository {

    public record SagaRow(String sagaId, String sagaName, SagaStatus status,
                          int currentStage, String failReason) {
    }

    public record StepRow(int stageIndex, int stepIndex, String stepName,
                          StepStatus status, int attempts, boolean compensated) {
    }

    private final DataSource dataSource;

    public SagaRepository(DataSource dataSource) {
        this.dataSource = dataSource;
        createSchema();
    }

    private void createSchema() {
        List<String> statements = List.of(
                """
                CREATE TABLE IF NOT EXISTS saga_instance (
                  saga_id       VARCHAR(64)   NOT NULL PRIMARY KEY,
                  saga_name     VARCHAR(128)  NOT NULL,
                  status        VARCHAR(32)   NOT NULL,
                  current_stage INT           NOT NULL,
                  fail_reason   VARCHAR(2048),
                  created_at    TIMESTAMP     NOT NULL,
                  updated_at    TIMESTAMP     NOT NULL
                )
                """,
                """
                CREATE TABLE IF NOT EXISTS step_instance (
                  saga_id      VARCHAR(64)   NOT NULL,
                  stage_index  INT           NOT NULL,
                  step_index   INT           NOT NULL,
                  step_name    VARCHAR(128)  NOT NULL,
                  status       VARCHAR(32)   NOT NULL,
                  attempts     INT           NOT NULL,
                  compensated  BOOLEAN       NOT NULL,
                  PRIMARY KEY (saga_id, stage_index, step_index)
                )
                """,
                """
                CREATE TABLE IF NOT EXISTS saga_event (
                  id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                  saga_id    VARCHAR(64)   NOT NULL,
                  event_type VARCHAR(64)   NOT NULL,
                  detail     VARCHAR(2048),
                  created_at TIMESTAMP     NOT NULL
                )
                """);
        try (Connection conn = dataSource.getConnection()) {
            for (String sql : statements) {
                try (PreparedStatement ps = conn.prepareStatement(sql)) {
                    ps.executeUpdate();
                }
            }
        } catch (SQLException e) {
            throw new IllegalStateException("failed to create saga schema", e);
        }
    }

    public void insertSaga(String sagaId, String sagaName) {
        String sql = "INSERT INTO saga_instance (saga_id, saga_name, status, current_stage, fail_reason, created_at, updated_at)"
                + " VALUES (?,?,?,?,NULL,?,?)";
        Timestamp now = Timestamp.from(Instant.now());
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, sagaId);
            ps.setString(2, sagaName);
            ps.setString(3, SagaStatus.RUNNING.name());
            ps.setInt(4, 0);
            ps.setTimestamp(5, now);
            ps.setTimestamp(6, now);
            ps.executeUpdate();
        } catch (SQLException e) {
            throw new IllegalStateException("failed to insert saga " + sagaId, e);
        }
    }

    public void insertStep(String sagaId, int stageIndex, int stepIndex, String stepName) {
        String sql = "INSERT INTO step_instance (saga_id, stage_index, step_index, step_name, status, attempts, compensated)"
                + " VALUES (?,?,?,?,?,0,FALSE)";
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, sagaId);
            ps.setInt(2, stageIndex);
            ps.setInt(3, stepIndex);
            ps.setString(4, stepName);
            ps.setString(5, StepStatus.PENDING.name());
            ps.executeUpdate();
        } catch (SQLException e) {
            throw new IllegalStateException("failed to insert step " + stepName, e);
        }
    }

    public void updateStatus(String sagaId, SagaStatus status) {
        execute("UPDATE saga_instance SET status=?, updated_at=? WHERE saga_id=?",
                ps -> {
                    ps.setString(1, status.name());
                    ps.setTimestamp(2, Timestamp.from(Instant.now()));
                    ps.setString(3, sagaId);
                });
    }

    public void updateCurrentStage(String sagaId, int stageIndex) {
        execute("UPDATE saga_instance SET current_stage=?, updated_at=? WHERE saga_id=?",
                ps -> {
                    ps.setInt(1, stageIndex);
                    ps.setTimestamp(2, Timestamp.from(Instant.now()));
                    ps.setString(3, sagaId);
                });
    }

    public void recordFailReason(String sagaId, String failReason) {
        execute("UPDATE saga_instance SET fail_reason=?, updated_at=? WHERE saga_id=?",
                ps -> {
                    ps.setString(1, failReason);
                    ps.setTimestamp(2, Timestamp.from(Instant.now()));
                    ps.setString(3, sagaId);
                });
    }

    public void updateStepStatus(String sagaId, int stageIndex, int stepIndex,
                                 StepStatus status, int attempts) {
        execute("UPDATE step_instance SET status=?, attempts=? WHERE saga_id=? AND stage_index=? AND step_index=?",
                ps -> {
                    ps.setString(1, status.name());
                    ps.setInt(2, attempts);
                    ps.setString(3, sagaId);
                    ps.setInt(4, stageIndex);
                    ps.setInt(5, stepIndex);
                });
    }

    public void markStepCompensated(String sagaId, int stageIndex, int stepIndex) {
        execute("UPDATE step_instance SET status=?, compensated=TRUE WHERE saga_id=? AND stage_index=? AND step_index=?",
                ps -> {
                    ps.setString(1, StepStatus.COMPENSATED.name());
                    ps.setString(2, sagaId);
                    ps.setInt(3, stageIndex);
                    ps.setInt(4, stepIndex);
                });
    }

    public SagaRow loadSaga(String sagaId) {
        String sql = "SELECT saga_id, saga_name, status, current_stage, fail_reason FROM saga_instance WHERE saga_id=?";
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, sagaId);
            try (ResultSet rs = ps.executeQuery()) {
                if (!rs.next()) {
                    throw new IllegalArgumentException("unknown saga " + sagaId);
                }
                return new SagaRow(rs.getString(1), rs.getString(2),
                        SagaStatus.valueOf(rs.getString(3)), rs.getInt(4), rs.getString(5));
            }
        } catch (SQLException e) {
            throw new IllegalStateException("failed to load saga " + sagaId, e);
        }
    }

    public List<SagaRow> incompleteSagas() {
        String sql = "SELECT saga_id, saga_name, status, current_stage, fail_reason FROM saga_instance"
                + " WHERE status IN ('RUNNING','COMPENSATING') ORDER BY created_at";
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {
            List<SagaRow> rows = new ArrayList<>();
            while (rs.next()) {
                rows.add(new SagaRow(rs.getString(1), rs.getString(2),
                        SagaStatus.valueOf(rs.getString(3)), rs.getInt(4), rs.getString(5)));
            }
            return rows;
        } catch (SQLException e) {
            throw new IllegalStateException("failed to query incomplete sagas", e);
        }
    }

    /**
     * Steps that may need compensation, in reverse execution order. A step qualifies
     * if it succeeded, or if its forward action was invoked but the outcome is unknown
     * (e.g. a timeout or a fault injected after the action) — detected via the
     * participant TRY barrier.
     */
    public List<StepRow> stepsAwaitingCompensation(String sagaId) {
        String sql = """
                SELECT s.stage_index, s.step_index, s.step_name, s.status, s.attempts, s.compensated
                FROM step_instance s
                WHERE s.saga_id = ?
                  AND s.compensated = FALSE
                  AND (s.status = 'SUCCEEDED'
                       OR EXISTS (SELECT 1 FROM participant_barrier b
                                  WHERE b.saga_id = s.saga_id
                                    AND b.step_name = s.step_name
                                    AND b.barrier_type = 'TRY'))
                ORDER BY s.stage_index DESC, s.step_index DESC
                """;
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, sagaId);
            try (ResultSet rs = ps.executeQuery()) {
                List<StepRow> rows = new ArrayList<>();
                while (rs.next()) {
                    rows.add(new StepRow(rs.getInt(1), rs.getInt(2), rs.getString(3),
                            StepStatus.valueOf(rs.getString(4)), rs.getInt(5), rs.getBoolean(6)));
                }
                return rows;
            }
        } catch (SQLException e) {
            throw new IllegalStateException("failed to query steps awaiting compensation", e);
        }
    }

    public void addEvent(String sagaId, String eventType, String detail) {
        String sql = "INSERT INTO saga_event (saga_id, event_type, detail, created_at) VALUES (?,?,?,?)";
        execute(sql, ps -> {
            ps.setString(1, sagaId);
            ps.setString(2, eventType);
            if (detail == null) {
                ps.setNull(3, Types.VARCHAR);
            } else {
                ps.setString(3, detail.length() > 2048 ? detail.substring(0, 2048) : detail);
            }
            ps.setTimestamp(4, Timestamp.from(Instant.now()));
        });
    }

    public List<SagaEvent> events(String sagaId) {
        String sql = "SELECT saga_id, event_type, detail, created_at FROM saga_event WHERE saga_id=? ORDER BY id";
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            ps.setString(1, sagaId);
            try (ResultSet rs = ps.executeQuery()) {
                List<SagaEvent> events = new ArrayList<>();
                while (rs.next()) {
                    events.add(new SagaEvent(rs.getString(1), rs.getString(2),
                            rs.getString(3), rs.getTimestamp(4).toInstant()));
                }
                return events;
            }
        } catch (SQLException e) {
            throw new IllegalStateException("failed to load events for saga " + sagaId, e);
        }
    }

    private void execute(String sql, SqlBinder binder) {
        try (Connection conn = dataSource.getConnection();
             PreparedStatement ps = conn.prepareStatement(sql)) {
            binder.bind(ps);
            ps.executeUpdate();
        } catch (SQLException e) {
            throw new IllegalStateException("statement failed: " + sql, e);
        }
    }

    @FunctionalInterface
    private interface SqlBinder {
        void bind(PreparedStatement ps) throws SQLException;
    }
}
